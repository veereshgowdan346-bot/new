"""
CHINTU AI TRADING SYSTEM - Authoritative Trade Provenance Framework (Phase 3 Hardened)
Classifies execution provenance across all historical and runtime trading records:

Provenances Defined:
- REAL_BROKER_EXECUTION: Authenticated real-order execution confirmed by live broker fill callback and contract note.
- AUTHENTIC_FEED_PAPER: Simulated paper fill derived from authentic exchange live tick stream during active market session.
- SYNTHETIC_SIMULATION: Script-generated or randomized simulated paper execution without independently recorded exchange ticks.
- SYNTHETIC_REPLAY: Fixed-target deterministic test-bench replay (e.g. +150.00 take-profit replays).
- TELEMETRY_TEST: Synthetic telemetry latency harness executions (e.g. fake tickers TEST_TELE_*).
- MOCK_BROKER: Test double executions generated by offline mock harnesses (e.g. FAKE_AO_1).
- SYNTHETIC_STRESS_TEST: Circuit breaker panic exit injections (e.g. IDs 737, 746, 751, 759).
- RMS_PRE_ORDER_REJECTION: Pre-trade risk control blocks (mode in RMS_CAPITAL_EXCEEDED, RMS_BLOCKED).
- INITIAL_ENTRY_ORDER: Open/entry position orders prior to closed trade exit.
- UNKNOWN_PROVENANCE: Ambiguous historical records lacking verifiable authentic source events.
"""

from typing import Dict, Any, Optional

PROVENANCE_REAL_BROKER = "REAL_BROKER_EXECUTION"
PROVENANCE_AUTHENTIC_FEED_PAPER = "AUTHENTIC_FEED_PAPER"
PROVENANCE_SYNTHETIC_SIMULATION = "SYNTHETIC_SIMULATION"
PROVENANCE_SYNTHETIC_REPLAY = "SYNTHETIC_REPLAY"
PROVENANCE_TELEMETRY_TEST = "TELEMETRY_TEST"
PROVENANCE_MOCK_BROKER = "MOCK_BROKER"
PROVENANCE_SYNTHETIC_STRESS_TEST = "SYNTHETIC_STRESS_TEST"
PROVENANCE_RMS_REJECTION = "RMS_PRE_ORDER_REJECTION"
PROVENANCE_INITIAL_ENTRY = "INITIAL_ENTRY_ORDER"
PROVENANCE_UNKNOWN = "UNKNOWN_PROVENANCE"

VALID_PROVENANCES = {
    PROVENANCE_REAL_BROKER,
    PROVENANCE_AUTHENTIC_FEED_PAPER,
    PROVENANCE_SYNTHETIC_SIMULATION,
    PROVENANCE_SYNTHETIC_REPLAY,
    PROVENANCE_TELEMETRY_TEST,
    PROVENANCE_MOCK_BROKER,
    PROVENANCE_SYNTHETIC_STRESS_TEST,
    PROVENANCE_RMS_REJECTION,
    PROVENANCE_INITIAL_ENTRY,
    PROVENANCE_UNKNOWN
}

# The 4 Phase 15 emergency panic exit test injection record IDs
SYNTHETIC_STRESS_IDS = {737, 746, 751, 759}

# Deterministic take-profit targets from historical offline test-bench runs
SYNTHETIC_REPLAY_TARGETS = {150.0, 85.0, 420.0, 120.0}


def classify_trade_provenance(record: Dict[str, Any]) -> str:
    """
    Deterministically determines the execution provenance of a trade record.
    Enforces strict evidentiary verification:
    - Never trusts claims of REAL_BROKER_EXECUTION without broker confirmation, LIVE mode, and non-mock ID.
    - Never trusts claims of AUTHENTIC_FEED_PAPER for randomized script simulations or closed market sessions.
    - Fails closed to UNKNOWN_PROVENANCE when evidence is missing or contradictory.
    """
    raw_id = record.get("id") or record.get("record_id") or 0
    try:
        rec_id = int(raw_id)
    except (ValueError, TypeError):
        rec_id = 0
    order_id = str(record.get("order_id") or record.get("orderId") or "").strip()
    mode = str(record.get("mode") or "").strip().upper()
    broker = str(record.get("broker") or "").strip()
    symbol = str(record.get("symbol") or "").strip()
    action = str(record.get("action") or "").strip().upper()
    analysis = str(record.get("post_trade_analysis") or "")

    raw_pnl_str = str(record.get("pnl") or "0").replace("₹", "").replace("$", "").replace(",", "").strip()
    raw_pnl_str = raw_pnl_str.replace("+", "").replace("\u2212", "-").replace("\u2013", "-").replace("\u2014", "-")
    try:
        pnl_val = float(raw_pnl_str)
        if record.get("is_positive") in (0, "0", False) and pnl_val > 0:
            pnl_val = -pnl_val
    except Exception:
        pnl_val = 0.0

    # 1. Hardened Verification of Explicit Claims
    explicit = record.get("provenance")
    if explicit in VALID_PROVENANCES and explicit != PROVENANCE_UNKNOWN:
        # A. If claiming REAL_BROKER_EXECUTION, strictly verify independent broker evidence
        if explicit == PROVENANCE_REAL_BROKER:
            is_broker_confirmed = bool(record.get("is_broker_confirmed", False))
            is_live_mode = (mode == "LIVE")
            is_valid_broker = broker in ("Angel One (SmartAPI)", "SmartAPI")
            is_not_mock_id = bool(order_id and not any(order_id.upper().startswith(p) for p in ("FAKE", "MOCK", "SIM", "TEST", "ORD-PENDING", "EXP_ORD")))
            if is_broker_confirmed and is_live_mode and is_valid_broker and is_not_mock_id:
                return PROVENANCE_REAL_BROKER
            # Evidence contradictory or missing: fail closed
            if any(order_id.upper().startswith(p) for p in ("FAKE", "MOCK")):
                return PROVENANCE_MOCK_BROKER
            return PROVENANCE_UNKNOWN

        # B. If claiming AUTHENTIC_FEED_PAPER, verify market tick source and reject simulations
        if explicit == PROVENANCE_AUTHENTIC_FEED_PAPER:
            is_random_sim = (
                bool(record.get("is_randomized_simulation", False))
                or order_id.startswith("EXP_ORD")
                or "SIMULATED SLIPPAGE" in analysis.upper()
                or "OFFLINE SYNTHETIC SIMULATION" in analysis.upper()
            )
            if is_random_sim:
                return PROVENANCE_SYNTHETIC_SIMULATION
            is_paper_mode = (mode == "PAPER")
            if is_paper_mode and "TEST_TELE" not in symbol:
                return PROVENANCE_AUTHENTIC_FEED_PAPER
            return PROVENANCE_UNKNOWN

        # Other non-authentic explicit categories (SYNTHETIC_REPLAY, SYNTHETIC_SIMULATION, etc.) accepted directly
        return explicit

    # 2. Check Pre-Order RMS Rejection
    if (order_id.startswith("RMS-") or 
        mode in ("RMS_CAPITAL_EXCEEDED", "RMS_BLOCKED") or 
        broker == "RMS Guard Engine" or
        "RMS-REJECTED" in order_id):
        return PROVENANCE_RMS_REJECTION

    # 3. Check Mock Test Double
    if (order_id.startswith("FAKE_AO") or 
        order_id in ("FAKE_AO_1", "FAKE_AO") or
        (mode == "LIVE" and "FakeBroker" in broker)):
        return PROVENANCE_MOCK_BROKER

    # 4. Check Initial Entry Orders
    # Position entries with 0.00 PnL (excluding scratch exits 732, 741)
    if action in ("BUY", "SELL") and abs(pnl_val) < 0.001 and rec_id not in (732, 741):
        return PROVENANCE_INITIAL_ENTRY

    # 5. Check Synthetic Emergency Exit Stress Tests
    if rec_id in SYNTHETIC_STRESS_IDS or (abs(pnl_val - (-45721.50)) < 0.01 and "EMERGENCY_EXIT_BYPASS" in analysis):
        return PROVENANCE_SYNTHETIC_STRESS_TEST

    # 6. Check Synthetic Telemetry Tests
    if "TEST_TELE" in symbol:
        return PROVENANCE_TELEMETRY_TEST

    # 7. Check Script / Randomized Simulations
    if (order_id.startswith("EXP_ORD") or 
        order_id.startswith("ORD-PENDING") or
        broker == "Paper Simulator" or
        record.get("is_randomized_simulation") or 
        "SIMULATED SLIPPAGE" in analysis.upper() or 
        "OFFLINE SYNTHETIC SIMULATION" in analysis.upper()):
        return PROVENANCE_SYNTHETIC_SIMULATION

    # 8. Check Synthetic Fixed-Target Replays
    # In historical records, take-profit values of exactly 150, 85, 420, 120 represent deterministic replays
    if round(abs(pnl_val), 2) in SYNTHETIC_REPLAY_TARGETS:
        return PROVENANCE_SYNTHETIC_REPLAY

    # 9. Check Confirmed Real Broker Executions (Inferred)
    is_broker_confirmed = bool(record.get("is_broker_confirmed", False))
    if (is_broker_confirmed and mode == "LIVE" and 
        broker in ("Angel One (SmartAPI)", "SmartAPI") and 
        order_id and not any(order_id.upper().startswith(p) for p in ("FAKE", "MOCK", "SIM", "TEST", "ORD-PENDING", "EXP_ORD"))):
        return PROVENANCE_REAL_BROKER

    # 10. Check Verified Authentic-Feed Paper Trades (Inferred)
    trade_id_str = str(record.get("trade_id", "") or "")
    is_authentic_feed = bool(record.get("is_authentic_feed", False)) or (
        mode == "PAPER" and (
            order_id.startswith("ORD_CONFIRMED") or 
            trade_id_str.startswith("CONFIRMED_PAPER") or 
            trade_id_str.startswith("TRD_QUAL")
        )
    )
    if is_authentic_feed and mode == "PAPER" and not "TEST_TELE" in symbol:
        return PROVENANCE_AUTHENTIC_FEED_PAPER

    # 11. Default: Unknown Provenance
    # Historical records without verifiable tick audit trail or broker confirmation
    return PROVENANCE_UNKNOWN


def is_verified_authentic(provenance: str) -> bool:
    """
    Returns True ONLY if the trade is a verified authentic execution:
    either real broker execution or authentic-feed paper trade.
    Returns False for all synthetic replays, simulations, mock doubles, telemetry runs, and unknown provenance.
    """
    return provenance in (PROVENANCE_REAL_BROKER, PROVENANCE_AUTHENTIC_FEED_PAPER)
